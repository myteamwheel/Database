import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {getDocument} from 'pdfjs-dist/legacy/build/pdf.mjs';
import {injuryReportTimestamp,latestInjuryReport,parseInjuryReportPages,reconcileInjuries} from '../scripts/lib/injury-report.mjs';
const read=f=>JSON.parse(fs.readFileSync(new URL('../scripts/data/live/'+f,import.meta.url),'utf8'));
const raw=read('injuries.json'),roster=read('roster.json');
const prefix='https://ak-static.cms.nba.com/referee/injury/Injury-Report_';
assert.equal(injuryReportTimestamp(prefix+'2026-10-26_10_30AM.pdf'),'2026-10-26T14:30:00.000Z');
assert.equal(injuryReportTimestamp(prefix+'2027-01-26_12_00PM.pdf'),'2027-01-26T17:00:00.000Z');
assert.throws(()=>injuryReportTimestamp(prefix+'2026-02-30_09_00AM.pdf'),/date/);
assert.throws(()=>injuryReportTimestamp(prefix+'2026-10-26_13_00AM.pdf'),/time/);
const selection=latestInjuryReport([prefix+'2026-10-26_09_00AM.pdf',prefix+'2026-10-26_10_30AM.pdf',prefix+'2026-10-26_11_00AM.pdf'].join(' '),'2026-10-26T14:45:00Z');
assert.ok(selection.url.includes('10_30AM'));
assert.throws(()=>latestInjuryReport(prefix+'2026-10-26_09_00AM.pdf','2026-10-30T14:00:00Z'),/stale/);
const bytes=Buffer.from(raw.pdfBase64,'base64');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),raw.pdfSha256);
const task=getDocument({data:new Uint8Array(bytes),useSystemFonts:true,disableFontFace:true});
const doc=await task.promise,pages=[];
try{for(let i=1;i<=doc.numPages;i++){const text=await(await doc.getPage(i)).getTextContent();pages.push(text.items.filter(i=>i.str?.trim()).map(i=>({text:i.str,x:i.transform[4],y:i.transform[5]})));}}finally{await task.destroy();}
assert.deepEqual(pages,raw.pages,'stored extraction must reproduce the original PDF exactly');
const parsed=parseInjuryReportPages(pages,raw),result=reconcileInjuries(parsed,roster);
assert.ok(parsed.rows.length>20&&parsed.notSubmitted.length>0);
assert.equal(result.confirmed.length+result.unresolved.length,parsed.rows.length);
assert.ok(parsed.rows.every(r=>r.name&&r.reason&&['Out','Questionable','Doubtful','Probable','Available'].includes(r.status)));
assert.throws(()=>parseInjuryReportPages([],{...raw}),/snapshot/);
assert.throws(()=>parseInjuryReportPages(pages,{...raw,source:prefix+'2026-10-26_09_00AM.pdf'}),/banner/);
const missingHeader=structuredClone(pages);missingHeader[0]=missingHeader[0].filter(i=>i.text.trim()!=='Player');
assert.throws(()=>parseInjuryReportPages(missingHeader,raw),/headers/);
const wrongRoster=structuredClone(roster);const id=wrongRoster.headers.indexOf('TEAM_ABBREVIATION');wrongRoster.rows.forEach(r=>r[id]='ATL');
assert.ok(reconcileInjuries(parsed,wrongRoster).unresolved.length>0);
console.log(`Official injury report: all ${pages.length} PDF pages reproduced; ${parsed.rows.length} player entries, ${parsed.notSubmitted.length} pending reports, time/season/source/missing-header controls passed.`);
